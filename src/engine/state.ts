import type { RelationsTable } from "../data/diplomacy";
import type { FactionId, ResourceId } from "../data/types";

/** Placed structure instance on a territory base grid. */
export interface PlacedBuilding {
  instanceId: string;
  buildingId: string;
  x: number;
  y: number;
  hp: number;
  /** Remaining construction ticks; 0 = complete. */
  buildRemaining: number;
  /** Workers assigned to staff this building. */
  workers: number;
}

/** Local training job in a territory queue. */
export interface TrainingJob {
  id: string;
  kind: "worker" | "unit";
  unitId?: string;
  count: number;
  turnsRemaining: number;
}

export interface TerritoryState {
  owner: FactionId;
  buildings: PlacedBuilding[];
  /** Local supply stockpile generated by depots (feeds invasions). */
  supplyStock: number;
  /** Untrained local population pool. */
  population: number;
  /** Trained workers available in this territory (unassigned pool). */
  workers: number;
  /** Units stationed on this plot (defend / launch invasions). */
  garrison: Record<string, number>;
  trainingQueue: TrainingJob[];
}

export interface PlayerState {
  id: FactionId;
  kind: "human" | "ai";
  displayName: string;
  resources: Record<ResourceId, number>;
  researched: string[];
  /**
   * Global staging pool (legacy / overflow). Prefer territorial garrisons.
   * Still used as a soft buffer when capturing / demobilizing.
   */
  reserves: Record<string, number>;
  /** Energy spent each turn on recruitment campaigning. */
  campaignBudget: number;
  /** True when energy went negative after upkeep (penalties apply). */
  insolvent?: boolean;
  /** Soft-eliminated — no territories left. */
  eliminated?: boolean;
}

/** Army marching between territories. */
export interface ArmyTransit {
  id: string;
  owner: FactionId;
  fromId: string;
  toId: string;
  force: StrikeForceSlot[];
  turnsRemaining: number;
  totalTurns: number;
}

/** After a successful attack, choose how many survivors occupy. */
export interface PendingCapture {
  territoryId: string;
  attacker: FactionId;
  /** Origin of the strike (survivors not occupying return here if friendly). */
  fromId: string | null;
  survivors: StrikeForceSlot[];
  /** Population left on the plot after capture retain. */
  population: number;
  workers: number;
}

/** Snapshot of AI invasion intent for UI / tests. */
export interface AiAttackPlan {
  fromId: string;
  toId: string;
  force: StrikeForceSlot[];
}

export interface StrikeForceSlot {
  unitId: string;
  count: number;
}

export interface BattleUnit {
  id: string;
  unitId: string;
  side: "attacker" | "defender";
  x: number;
  y: number;
  hp: number;
  maxHp: number;
  cooldown: number;
  anim: "idle" | "move" | "attack" | "hit" | "destroyed";
  animT: number;
  alive: boolean;
  /** Temporary EMP disable timer (seconds). */
  disabledT: number;
  /** Smooth facing angle (radians); 0 = +X / east. */
  facing: number;
}

export interface BattleDefense {
  id: string;
  buildingId: string;
  instanceId: string;
  x: number;
  y: number;
  hp: number;
  maxHp: number;
  cooldown: number;
  anim: "idle" | "firing" | "destroyed" | "working";
  animT: number;
  alive: boolean;
  disabledT: number;
  /** Turret aim angle (radians); 0 = +X. */
  facing: number;
}

export interface BattleProjectile {
  id: string;
  style: string;
  x: number;
  y: number;
  tx: number;
  ty: number;
  progress: number;
  speed: number;
  damage: number;
  damageType: string;
  targetKind: "unit" | "defense";
  targetId: string;
}

export interface BattleExplosion {
  id: string;
  x: number;
  y: number;
  t: number;
  style: string;
}

/** Persistent ground burn mark left after an explosion. */
export interface BattleScorch {
  id: string;
  x: number;
  y: number;
  /** Age in seconds — fades slowly. */
  t: number;
  /** Relative size (1 ≈ tank footprint). */
  scale: number;
}

export interface BattleState {
  territoryId: string;
  attacker: FactionId;
  defender: FactionId;
  units: BattleUnit[];
  defenses: BattleDefense[];
  projectiles: BattleProjectile[];
  explosions: BattleExplosion[];
  scorches: BattleScorch[];
  time: number;
  elapsed: number;
  status: "running" | "attacker_win" | "defender_win";
  log: string[];
}

export type Screen =
  | "menu"
  | "lobby"
  | "map"
  | "base"
  | "research"
  | "invade"
  | "battle"
  | "capture"
  | "save"
  | "victory";

export interface GameState {
  version: 1;
  seed: number;
  turn: number;
  phase: "play" | "battle" | "capture" | "ended";
  activePlayerIndex: number;
  playerOrder: FactionId[];
  players: Record<string, PlayerState>;
  territories: Record<string, TerritoryState>;
  battle: BattleState | null;
  selectedTerritoryId: string | null;
  screen: Screen;
  multiplayerMode: "solo" | "hotseat" | "lan";
  winner: FactionId | null;
  message: string | null;
  nextInstanceId: number;
  /** Last AI multi-front attack plan (for map arrows / debugging). */
  aiAttackPlans: AiAttackPlan[];
  /** Armies currently marching. */
  armiesInTransit: ArmyTransit[];
  /** Capture occupation choice pending after attacker win. */
  pendingCapture: PendingCapture | null;
  /** Recent AI / system notices (elimination, arrivals, AI summary). */
  turnLog: string[];
  /** Diplomacy hook — unused in combat until a future pass. */
  relations: RelationsTable;
}

export function emptyResources(): Record<ResourceId, number> {
  return { energy: 0, alloy: 0, research: 0, supply: 0 };
}
