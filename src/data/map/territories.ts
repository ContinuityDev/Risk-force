import type { TerritoryDef } from "../types";

/**
 * Risk-style Earth — territories are non-overlapping partitions with shared borders.
 * viewBox 0 0 1000 520. Every polygon sits inside its continent silhouette.
 *
 * Shared-edge rule: adjacent territories reuse the exact same edge coordinates
 * so fills tile cleanly with no overlap and no gaps.
 */

function box(x0: number, y0: number, x1: number, y1: number): string {
  return `M ${x0},${y0} L ${x1},${y0} L ${x1},${y1} L ${x0},${y1} Z`;
}

function quad(
  a: [number, number],
  b: [number, number],
  c: [number, number],
  d: [number, number],
): string {
  return `M ${a[0]},${a[1]} L ${b[0]},${b[1]} L ${c[0]},${c[1]} L ${d[0]},${d[1]} Z`;
}

